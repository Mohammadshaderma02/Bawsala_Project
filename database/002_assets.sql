CREATE TABLE dbo.Assets
(
    Id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Assets PRIMARY KEY,
    AssetKey NVARCHAR(120) NOT NULL CONSTRAINT UQ_Assets_AssetKey UNIQUE,
    FileName NVARCHAR(255) NULL,
    MimeType NVARCHAR(120) NOT NULL,
    Base64Content NVARCHAR(MAX) NOT NULL,
    AltEn NVARCHAR(250) NULL,
    AltAr NVARCHAR(250) NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_Assets_IsActive DEFAULT (1),
    CreatedAtUtc DATETIME2 NOT NULL CONSTRAINT DF_Assets_CreatedAtUtc DEFAULT (SYSUTCDATETIME())
);

CREATE INDEX IX_Assets_AssetKey_IsActive
ON dbo.Assets(AssetKey, IsActive);
